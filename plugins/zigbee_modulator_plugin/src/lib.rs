pub const SHAPE: [f32; 4] = [0.0, 0.707_106_77, 1.0, 0.707_106_77];

pub fn make_nibble(i: u8) -> impl Iterator<Item = Complex32> + Send {
    DSSS[i as usize]
        .iter()
        .flat_map(|x| [x; 4])
        .zip(SHAPE.iter().cycle())
        .map(|(x, y)| x * y)
}

plugin_api::export_plugin! {
    name: "ZigbeeModulator",
    description: "ZigBee DSSS modulator (O-QPSK with half-sine pulse shaping)",
    config: (),
    create: |_cfg, _id| {
        ApplyIntoIter::<_, _, _>::new(|i: &u8| {
            make_nibble(i & 0x0F).chain(make_nibble(i >> 4))
        })
    }
}
